/// Ostersonntag im gregorianischen Kalender (Gaußsche Osterformel in der
/// Fassung von Meeus/Jones/Butcher).
DateTime ostersonntag(int year) {
  final a = year % 19;
  final b = year ~/ 100;
  final c = year % 100;
  final d = b ~/ 4;
  final e = b % 4;
  final f = (b + 8) ~/ 25;
  final g = (b - f + 1) ~/ 3;
  final h = (19 * a + b - d - g + 15) % 30;
  final i = c ~/ 4;
  final k = c % 4;
  final l = (32 + 2 * e + 2 * i - h - k) % 7;
  final m = (a + 11 * h + 22 * l) ~/ 451;
  final month = (h + l - 7 * m + 114) ~/ 31;
  final day = (h + l - 7 * m + 114) % 31 + 1;
  return DateTime(year, month, day);
}

/// Der vierte Advent: der letzte Sonntag vor dem 25. Dezember.
DateTime _fourthAdvent(int year) {
  var d = DateTime(year, 12, 24);
  while (d.weekday != DateTime.sunday) {
    d = addDays(d, -1);
  }
  return d;
}

DateTime _nthWeekday(int year, int month, int weekday, int n) {
  final first = DateTime(year, month, 1);
  final offset = (weekday - first.weekday + 7) % 7;
  return DateTime(year, month, 1 + offset + 7 * (n - 1));
}

DateTime _lastWeekday(int year, int month, int weekday) {
  final last = DateTime(year, month + 1, 0);
  final offset = (last.weekday - weekday + 7) % 7;
  return DateTime(year, month, last.day - offset);
}
