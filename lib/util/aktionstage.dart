/// Ein Aktionstag, Gedenktag oder Feiertag. [witzig] trennt die Tage zum
/// Schmunzeln (Tag der Jogginghose) von den ernsten (Weltkrebstag).
class Aktionstag {
  const Aktionstag(this.name, this.info, {required this.witzig});

  final String name;
  final String info;
  final bool witzig;

  @override
  String toString() => name;
}

/// Alle Aktionstage an [day], zuerst die ernsten, dann die witzigen.
List<Aktionstag> aktionstageAm(DateTime day) {
  final d = dateOnly(day);
  final all = <Aktionstag>[
    for (final e in _fest)
      if (e.$1 == d.month && e.$2 == d.day)
        Aktionstag(e.$4, e.$5, witzig: e.$3),
    ..._beweglich(d),
  ];
  return [...all.where((t) => !t.witzig), ...all.where((t) => t.witzig)];
}

/// Der nächste Tag nach [day] (höchstens ein Jahr voraus), an dem es
/// Aktionstage gibt, samt den Tagen selbst.
(DateTime, List<Aktionstag>)? naechsteAktionstage(DateTime day) {
  for (var i = 1; i <= 366; i++) {
    final next = addDays(dateOnly(day), i);
    final list = aktionstageAm(next);
    if (list.isNotEmpty) return (next, list);
  }
  return null;
}

